// Screen language: Korean (default text in the code), English, Simplified Chinese.
// t("한국어 문구") returns the phrase in the chosen language; {name} parts are filled from `vars`.
// This only changes buttons and messages. Word explanations always come in Korean + English.
const KEY = "wb_lang";
export const LANGS = [["ko", "한국어"], ["en", "English"], ["zh", "中文"]];

function detect() {
  const saved = localStorage.getItem(KEY);
  if (LANGS.some(([id]) => id === saved)) return saved;
  const browser = (navigator.language || "ko").toLowerCase();
  return browser.startsWith("zh") ? "zh" : browser.startsWith("en") ? "en" : "ko";
}

let lang = detect();
document.documentElement.lang = lang;

export const getLang = () => lang;
export const hasChosenLang = () => localStorage.getItem(KEY) !== null;
export const locale = () => ({ ko: "ko-KR", en: "en-US", zh: "zh-CN" })[lang];

export function setLang(next) {
  lang = next;
  localStorage.setItem(KEY, next);
  document.documentElement.lang = next;
}

export function t(key, vars) {
  let text = lang === "ko" ? key : T[key]?.[lang === "en" ? 0 : 1] ?? key;
  for (const [name, value] of Object.entries(vars || {})) text = text.replaceAll(`{${name}}`, value);
  return text;
}

// An explanation of several sentences reads better with each sentence on its own line, so a line
// break goes between them. Only for explanations (see tidyParagraphs in app.js): never for what a
// character says, a toast, a banner or a button. Very short pieces such as "정답! 대단해요!" stay
// together, and so do things like "e.g. this".
export function sentences(text) {
  if (text.length < 30 || !/[.!?。！？] /.test(text)) return text;
  const parts = text.split(/(?<=[.!?。！？]) +(?=(?![a-z])[\p{L}\p{N}"“‘'(+{])/u);
  let out = parts[0], line = parts[0].length;
  for (const part of parts.slice(1)) {
    const apart = line >= 12 && part.length >= 8;
    out += (apart ? "\n" : " ") + part;
    line = apart ? part.length : line + 1 + part.length;
  }
  return out;
}

